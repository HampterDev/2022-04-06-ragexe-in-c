"""Write tests/window_lists_stubs.c, the recording stubs of test_window_lists.

Usage: make_window_lists_stubs.py <preprocessed .i files...> --names <file> --out <file>
The .i files are `cl /P` of the eight window-list files that build_window_lists.bat compiles
(same /I options). <names> lists the symbols they use from the rest of the client, one per
line without the leading underscore: the unresolved externals of linking them alone with
std/list.c, std/tree.c and an empty main (`link /FORCE:UNRESOLVED`). Rerun it when the
window-list files start calling something new. Every function becomes a stub that records its
name and arguments through window_lists_trace.h and returns:
  - a new fake window for the window constructors (*_new, ui_*_create returning a pointer,
    except ui_window_create);
  - its first argument for the *_construct functions, made a fake window in place
    (wl_construct);
  - wl_env_ptr() for other pointers and wl_env_int() for numbers, which the test switches
    between "everything absent" (NULL and 0) and "everything present" (a zeroed dummy block
    and 1).
Arguments are recorded as numbers, strings (char pointers and struct String) or named
pointers; other structs passed by value are not recorded. The functions the test writes itself (HAND_WRITTEN) and the names
starting with g_ (data, and the function g_resMgr) are skipped; the test defines them.
"""
import re
import sys

args = sys.argv[1:]
names_file = args[args.index('--names') + 1]
out_file = args[args.index('--out') + 1]
inputs = [a for a in args if a.endswith('.i')]
names = [n.strip() for n in open(names_file) if n.strip()]

TYPE_WORDS = {'int', 'char', 'short', 'long', 'unsigned', 'signed', 'float', 'double', 'void', 'BYTE',
              'WORD', 'DWORD', 'size_t', 'BOOL', 'UINT', 'INT_PTR', 'HWND', 'LPARAM', 'WPARAM'}
HAND_WRITTEN = {'client_lua_call', 'ui_window_create', 'mem_alloc', 'mem_free', 'string_free',
                'string_assign_cstr', 'string_equal_cstr', 'msg_str', 'ui_skin_path', 'ui_window_to_screen',
                'ui_window_mgr_add_window', 'rag_connection_send_packet'}

text = ''
for path in inputs:
    for line in open(path, encoding='utf-8', errors='replace'):
        if line.startswith('#'):
            continue
        text += line
text = re.sub(r'\s+', ' ', text)

out = ['/* Generated by tests/make_window_lists_stubs.py: recording stubs for test_window_lists.c. */',
       '#include "window_lists_trace.h"', '#include "std/string.h"', '']
decls = []
for name in names:
    if name.startswith(('g_', 's_')) or name in HAND_WRITTEN:
        continue
    found = None
    for m in re.finditer(r'\b' + name + r' ?\(', text):
        depth, j = 0, m.end() - 1
        while True:
            depth += {'(': 1, ')': -1}.get(text[j], 0)
            if depth == 0:
                break
            j += 1
        if not re.match(r' ?;', text[j + 1:]):
            continue
        start = max(text.rfind(';', 0, m.start()), text.rfind('}', 0, m.start()), text.rfind('{', 0, m.start()))
        ret = text[start + 1:m.start()].strip()
        if not re.fullmatch(r'[A-Za-z_][\w \*()]*', ret) or ret.split()[0] in (
                'return', 'case', 'default', 'else', 'do', 'if', 'while', 'for', 'switch'):
            continue
        found = (ret, text[m.end():j])
    if not found:
        sys.exit(f'no declaration for {name}')
    ret = found[0].strip()
    ret = re.sub(r'^(extern |__declspec\(\w+\) )+', '', ret).strip()
    params = found[1].strip()
    decls.append((name, ret, params))

for name, ret, params in decls:
    plist = [] if params in ('', 'void') else [p.strip() for p in params.split(',')]
    named = []
    for i, p in enumerate(plist):
        if p == '...':
            named.append(('...', None, 'skip'))
            continue
        m = re.fullmatch(r'(.*?[\s\*])([A-Za-z_]\w*)', p)
        if m and m.group(2) not in TYPE_WORDS and m.group(1).strip() not in ('struct', 'enum', 'union'):
            p = m.group(1).strip()
        kind = ('str' if p in ('const char *', 'char *') else 'ptr' if '*' in p else
                'float' if p in ('float', 'double') else 'string' if p == 'struct String' else
                'skip' if p.startswith('struct ') else 'int')
        named.append((f'{p} a{i}', p, kind))
    sig = ', '.join(n for n, _, _ in named) or 'void'
    body = [f'    wl_call("{name}");']
    for i, (n, p, kind) in enumerate(named):
        if kind == 'str':
            body.append(f'    wl_str(a{i});')
        elif kind == 'string':
            body.append(f'    wl_str(string_cstr(&a{i}));')
        elif kind == 'ptr':
            body.append(f'    wl_ptr(a{i});')
        elif kind == 'int':
            body.append(f'    wl_int((long long)a{i});')
        elif kind == 'float':
            body.append(f'    wl_float((double)a{i});')
    body.append('    wl_end();')
    is_ptr = ret.endswith('*')
    if ret == 'void':
        pass
    elif is_ptr and (name.endswith('_new') or (name.endswith('_create') and name.startswith('ui'))):
        body.append(f'    return ({ret})wl_fake_window("{name}");')
    elif is_ptr and name.endswith('_construct'):
        body.append(f'    wl_construct(a0, "{name}");')
        body.append(f'    return a0;')
    elif is_ptr:
        body.append(f'    return ({ret})wl_env_ptr();')
    elif ret in ('float', 'double'):
        body.append(f'    return ({ret})wl_env_int();')
    else:
        body.append(f'    return ({ret})wl_env_int();')
    out.append(f'{ret} {name}({sig})\n{{\n' + '\n'.join(body) + '\n}\n')

open(out_file, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
print(len(decls), 'stubs')
