"""extract_functions.py <root> <out.inc> <item>...

Copies production functions out of the tree into one include file, so an oracle test can link a
lookup without the file it lives in (and that file's dependencies). An item is
`path::signature`, the start of a top-level definition (`int session_remap_job(`), copied to the
closing brace at column 0; or `path::line::text`, one exact line (a file-local struct or table).
Each item must match exactly once."""
from pathlib import Path
import re
import sys

root, out = Path(sys.argv[1]), Path(sys.argv[2])
parts = []
for item in sys.argv[3:]:
    path, what = item.split('::', 1)
    source = (root / path).read_text(encoding='utf-8')
    if what.startswith('line::'):
        text = what[len('line::'):]
        assert source.count('\n' + text + '\n') == 1, item
        parts.append(text)
        continue
    matches = list(re.finditer(r'^' + re.escape(what) + r'[^{;]*\n\{', source, re.M))
    assert len(matches) == 1, item
    start = matches[0].start()
    parts.append(source[start:source.index('\n}', start) + 2])
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('/* generated by tests/oracle/extract_functions.py: production code copied for a test */\n\n'
               + '\n\n'.join(parts) + '\n', encoding='utf-8')
print(f'{out}: {len(parts)} items')
