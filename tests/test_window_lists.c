static unsigned char *take_block(struct Block *blocks, int *count)
{
    struct Block *block;

    assert(*count < MAX_BLOCKS);
    block = &blocks[(*count)++];
    if (!block->data) {
        block->data = malloc(BLOCK);
        assert(block->data);
    }
    memset(block->data, 0, BLOCK);
    block->used = 1;
    return block->data;
}

