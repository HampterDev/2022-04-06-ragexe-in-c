void *mem_alloc(size_t bytes)
{
    unsigned char *p = malloc(bytes ? bytes : 1);

    assert(p && heap_count < MAX_HEAP);
    memset(p, 0xcd, bytes);
    heap[heap_count].data = p;
    heap[heap_count].size = bytes;
    ++heap_count;
    return p;
}

void mem_free(void *memory)
{
    int k;

    if (!memory)
        return;
    for (k = 0; k < heap_count; ++k)
        if (heap[k].data == memory) {
            heap[k].data = NULL;
            free(memory);
            return;
        }
    fprintf(stderr, "mem_free of a block mem_alloc did not return\n");
    abort();
}

