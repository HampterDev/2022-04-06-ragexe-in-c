/* Characterization of the window-ID lists of the window manager, before they become one table.

   The four views of a window ID are compiled for real:
   - the factory: ui_window_mgr_make_window and the wm_make_* functions (make_window*.c);
   - the slots: ui_window_mgr_get_window, ui_window_mgr_is_untracked_id and
     ui_window_mgr_post_quit1 (window_slots.c);
   - forgetting a destroyed window: ui_window_mgr_forget_window (forget_window.c);
   - the teardown: ui_window_mgr_clear_slots and ui_window_mgr_close_all_windows (teardown.c).
   Everything else is a recording stub (window_lists_stubs.c, generated by
   make_window_lists_stubs.py, and the hand-written ones below). Window constructors return
   fake windows: zeroed blocks whose ops record every call.

   For every window ID from 0 to LAST_ID, in two environments (every stub returns NULL and 0,
   or a zeroed block and 1), on a freshly built window manager each time, the test records:
     make    ui_window_mgr_make_window(id), then get_window(id) and is_untracked_id(id);
     again   a second make_window(id) after the first;
     close   post_quit1(id) after make_window(id), and post_quit1(id) on a fresh manager;
     forget  forget_window(W) for every fake window W that make_window(id) created;
     clear   clear_slots after make_window(id);
     closeall  close_all_windows after make_window(id).
   And for every window field of the manager (not by ID): whether forget_window clears it,
   and whether clear_slots clears it.

   What is recorded: every stub call and every fake-window op with its arguments; the fields
   of the window manager that changed, by name (a window is named W<n> by creation order, an
   environment block D<n>, a heap block H<n>, a manager field mgr.<name>); the changed words of
   g_session1, g_navi and g_snapMgr; the words a fake window holds afterwards; return values.
   Pointers that none of these names covers stop the test. The lines go into a 64-bit FNV-1a
   digest; --trace FILE writes them as text.

   The manager fields are named through WL_MGR_FIELDS below, not through their offsets, so the
   digest stays the same when the fields move (a window table may replace the named slots);
   such a change updates WL_MGR_FIELDS to the new places of the same names. */
