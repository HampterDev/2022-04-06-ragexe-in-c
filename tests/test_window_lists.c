#define FIELD_COUNT (sizeof fields / sizeof fields[0])

static int name_pointer(char *out, size_t size, uintptr_t p)
{
    uintptr_t mgr = (uintptr_t)&g_windowMgr;
    size_t i;
    int k;

    if (!p)
        return snprintf(out, size, "0");
    for (k = 0; k < fake_count; ++k) {
        uintptr_t base = (uintptr_t)fakes[k].data;
        if (p >= base && p < base + BLOCK)
            return p == base ? snprintf(out, size, "W%d", k) : snprintf(out, size, "W%d+%#x", k, (unsigned)(p - base));
    }
    for (k = 0; k < env_count; ++k) {
        uintptr_t base = (uintptr_t)envs[k].data;
        if (p >= base && p < base + BLOCK)
            return p == base ? snprintf(out, size, "D%d", k) : snprintf(out, size, "D%d+%#x", k, (unsigned)(p - base));
    }
    if (p >= mgr && p < mgr + sizeof g_windowMgr) {
        size_t off = p - mgr;
        if (!off)
            return snprintf(out, size, "mgr");
        for (i = 0; i < FIELD_COUNT; ++i)
            if (off >= fields[i].offset && off < fields[i].offset + fields[i].size)
                return off == fields[i].offset ? snprintf(out, size, "mgr.%s", fields[i].name)
                                               : snprintf(out, size, "mgr.%s+%#x", fields[i].name,
                                                          (unsigned)(off - fields[i].offset));
        return snprintf(out, size, "mgr+%#x", (unsigned)off);
    }
    for (i = 0; i < sizeof globals / sizeof globals[0]; ++i) {
        uintptr_t base = (uintptr_t)globals[i].base;
        if (p >= base && p < base + globals[i].size)
            return p == base ? snprintf(out, size, "%s", globals[i].name)
                             : snprintf(out, size, "%s+%#x", globals[i].name, (unsigned)(p - base));
    }
    for (k = 0; k < heap_count; ++k) {
        uintptr_t base = (uintptr_t)heap[k].data;
        if (heap[k].data && p >= base && p < base + heap[k].size)
            return p == base ? snprintf(out, size, "H%d", k) : snprintf(out, size, "H%d+%#x", k, (unsigned)(p - base));
    }
    return -1;
}

static void put_pointer(const void *pointer)
{
    char name[96];

    if (name_pointer(name, sizeof name, (uintptr_t)pointer) < 0) {
        fprintf(stderr, "unnamed pointer while recording: %s\n", line);
        abort();
    }
    put("%s", name);
}

/* A number that may be a pointer passed as an int. */
static void put_value(long long value)
{
    char name[96];

    if (value >= 0x10000 && (uintptr_t)value == (uintptr_t)(unsigned long long)value &&
        name_pointer(name, sizeof name, (uintptr_t)value) >= 0)
        put("%s", name);
    else
        put("%lld", value);
}

void wl_call(const char *name)
{
    assert(line_len == 0);
    put("%s(", name);
    line_args = 0;
}

static void separate(void)
{
    if (line_args++)
        put(", ");
}

void wl_int(long long value)
{
    separate();
    put_value(value);
}

void wl_float(double value)
{
    separate();
    put("%g", value);
}

