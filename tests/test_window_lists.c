static uint64_t digest = UINT64_C(14695981039346656037);
static unsigned long long line_count;
static FILE *trace_file;
static char line[16384];
static size_t line_len;
static int line_args, quiet, environment;

static void put(const char *format, ...)
{
    va_list args;
    int n;

    va_start(args, format);
    n = vsnprintf(line + line_len, sizeof line - line_len, format, args);
    va_end(args);
    assert(n >= 0 && (size_t)n < sizeof line - line_len);
    line_len += (size_t)n;
}

static void emit(void)
{
    size_t i;

    if (!quiet) {
        for (i = 0; i < line_len; ++i) {
            digest ^= (unsigned char)line[i];
            digest *= UINT64_C(1099511628211);
        }
        digest ^= '\n';
        digest *= UINT64_C(1099511628211);
        ++line_count;
        if (trace_file) {
            fprintf(trace_file, "%s\n", line);
            fflush(trace_file);
        }
    }
    line_len = 0;
    line[0] = 0;
}

static void note(const char *format, ...)
{
    va_list args;
    int n;

    assert(line_len == 0);
    va_start(args, format);
    n = vsnprintf(line, sizeof line, format, args);
    va_end(args);
    assert(n >= 0 && (size_t)n < sizeof line);
    line_len = (size_t)n;
    emit();
}

