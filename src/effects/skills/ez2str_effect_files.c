static const struct str_file *find_str_file(int type)
{
    int lo = 0, hi = (int)(sizeof str_files / sizeof str_files[0]) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (str_files[mid].type == type)
            return &str_files[mid];
        if (str_files[mid].type < type)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return 0;
}

static void open_str_file(struct Ez2StrParticle *p, const struct str_file *f)
{
    switch (f->how) {
    case STR_LOAD:
        load(p, f->min_path && g_session1.map_rule_flags[0] == 1 ? f->min_path : f->path);
        break;
    case STR_OPEN:
        ez2_str_particle_open(p, f->path);
        break;
    case STR_LOAD_FULL_ONLY:
        if (g_session1.map_rule_flags[0] == 0)
            load(p, f->path);
        break;
    }
}

void ez2_str_effect_open_for_type(struct Ez2StrEffect *self,
                                           struct Ez2StrParticle *p, int type)
{
    char s[256];

    switch (type) {
    case 141:
        snprintf(s, sizeof s, "Pneuma%d.str", rand_below(3) + 1);
        ez2_str_particle_load(p, s);
        break;
    case 1163: {
        snprintf(s, sizeof s, "MeteorStorm\\meteor%d.str", rand_below(3) + 1);
        load(p, s);
        break;
    }
    case 1244: case 1245: case 1246: case 1247: case 1248:
    case 1249: case 1250: case 1251: case 1252: case 1253:
        snprintf(s, sizeof s, "test_effect\\%02d\\%02d.str", type - 1244, type - 1244);
        ez2_str_particle_load(p, s);
        break;
    case 1412:
        ez2_str_particle_load(p, string_cstr(&self->str_name));
        break;
    default: {
        const struct str_file *f = find_str_file(type);
        if (f)
            open_str_file(p, f);
        break;
    }
    }

    if (type >= 2384) {
        const char *name = 0;

        client_lua_call(g_session1.luaState, "GetHatEfResName", "d>s", type - 2384, &name);
        if (name)
            load(p, name);
    }
}
