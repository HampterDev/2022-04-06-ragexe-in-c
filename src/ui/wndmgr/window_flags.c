static void set_flags(struct UIWindowMgr *self, int kind, const unsigned short *ids, size_t count, int value)
{
    size_t i;

    for (i = 0; i < count; i++)
        self->window_flags[ids[i]][kind] = value;
}

#define SET_FLAGS(self, kind, ids, value) set_flags((self), (kind), (ids), sizeof(ids) / sizeof((ids)[0]), (value))

void ui_window_mgr_init_window_flags(struct UIWindowMgr *self)
{
    int id, kind;

    for (id = 0; id < WINDOW_FLAG_IDS; id++)
        for (kind = 0; kind < 8; kind++)
            self->window_flags[id][kind] = kind == UI_WNDFLAG_COMMANDS;
    SET_FLAGS(self, UI_WNDFLAG_COMMANDS, commands_off, 0);
    SET_FLAGS(self, UI_WNDFLAG_COMMANDS, commands_on, 1);
    SET_FLAGS(self, 5, kind5_on, 1);
    SET_FLAGS(self, UI_WNDFLAG_SEND_EDITS, send_edits_on, 1);
    SET_FLAGS(self, 7, kind7_on, 1);
}

int ui_window_mgr_get_window_flag(struct UIWindowMgr *self, int kind, int window_id)
{
    if (kind == UI_WNDFLAG_COMMANDS && !g_replayPlaying)
        return 1;
    if (kind < 0 || kind >= 8 || (unsigned)window_id >= WINDOW_FLAG_IDS)
        return 0;
    return self->window_flags[window_id][kind];
}
