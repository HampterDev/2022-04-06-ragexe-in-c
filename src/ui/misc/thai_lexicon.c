struct ThaiLexNode {
    BYTE ch;
    BYTE is_word;
    struct ThaiLexNode *next;
    struct ThaiLexNode *child;
};
SIZE_ASSERT(ThaiLexNode, 0xc);

struct ThaiLexicon {
    struct ThaiLexNode *root;
    int words;
    int nodes;
    int data_size;
    BYTE *data;
    BYTE header[0x104];
    int file_words;
    int file_nodes;
    int file_check;
    int file_size;
    BYTE loaded;
};
OFFSET_ASSERT(ThaiLexicon, file_words, 0x118);
SIZE_ASSERT(ThaiLexicon, 0x12c);
#define THAI_LEX_HEADER_SIZE 0x118

struct ThaiLexicon *thai_lexicon_construct(struct ThaiLexicon *self)
{
    self->root = NULL;
    self->words = 0;
    self->data_size = 0;
    self->nodes = 0;
    self->data = NULL;
    memset(self->header, 0, THAI_LEX_HEADER_SIZE);
    return self;
}

void thai_lexicon_free_nodes(struct ThaiLexicon *self, struct ThaiLexNode *node)
{
    if (!node)
        return;
    thai_lexicon_free_nodes(self, node->child);
    thai_lexicon_free_nodes(self, node->next);
    mem_free(node);
}

void thai_lexicon_destruct(struct ThaiLexicon *self)
{
    struct ThaiLexNode *root;

    if (self->data)
        mem_free(self->data);
    root = self->root;
    if (root) {
        thai_lexicon_free_nodes(self, root->child);
        thai_lexicon_free_nodes(self, root->next);
        mem_free(root);
    }
}

void thai_break_iterator_delete_lexicon(struct ThaiBreakIterator *self)
{
    struct ThaiLexicon *lexicon = self->lexicon;

    if (!lexicon)
        return;
    thai_lexicon_destruct(lexicon);
    mem_free(lexicon);
}

BYTE thai_break_iterator_initialize_lexicon(struct ThaiBreakIterator *self)
{
    struct ThaiLexicon *lexicon = self->lexicon;
    struct File file;
    BYTE loaded = 0;
    void *mem;

    if (lexicon) {
        thai_lexicon_destruct(lexicon);
        mem_free(lexicon);
    }
    mem = mem_alloc(sizeof *lexicon);
    lexicon = mem ? thai_lexicon_construct((struct ThaiLexicon *)mem) : NULL;
    self->lexicon = lexicon;
    file_construct(&file);
    if (file_open(&file, "..\\ftwrk.lex", 0, 1, 0)) {
        if (file_read(&file, lexicon->header, THAI_LEX_HEADER_SIZE) &&
            lexicon->file_check == lexicon->file_nodes + lexicon->file_words * 2 &&
            (lexicon->data = (BYTE *)mem_alloc(lexicon->file_size)) != NULL &&
            file_read(&file, lexicon->data, lexicon->file_size)) {
            lexicon->words = lexicon->file_words;
            lexicon->nodes = lexicon->file_nodes;
            lexicon->data_size = lexicon->file_size;
            loaded = 1;
        } else if (lexicon->data) {
            mem_free(lexicon->data);
            lexicon->data = NULL;
        }
        lexicon->loaded = loaded;
    }
    file_destruct(&file);
    memcpy(self->classes, thai_character_classes, sizeof self->classes);
    return self->lexicon != NULL;
}
