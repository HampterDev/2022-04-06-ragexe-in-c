#define COUNT_OF(a) (sizeof(a) / sizeof((a)[0]))

static void packet_table_insert(struct PacketTable *self, const struct PacketLengthRow *row)
{
    struct PacketLengthEntry entry;

    entry.id = row->id;
    entry.length.size = row->size;
    entry.length.min_size = row->min_size;
    tree_add(&self->lengths, &entry, sizeof entry, tree_less_int, NULL);
}

static void packet_table_insert_rows(struct PacketTable *self, const struct PacketLengthRow *rows, size_t count)
{
    size_t i;

    for (i = 0; i < count; i++)
        packet_table_insert(self, &rows[i]);
}

struct PacketTable *packet_table_construct(struct PacketTable *self)
{
    size_t i;

    tree_init(&self->lengths);
    packet_table_insert_rows(self, k_packetLengthsFirst, COUNT_OF(k_packetLengthsFirst));
    packet_table_insert_rows(self, k_packetLengths, COUNT_OF(k_packetLengths));
    for (i = 0; i < COUNT_OF(k_packetNames); i++)
        self->names[k_packetNames[i].id] = k_packetNames[i].name;
    return self;
}

void packet_table_destruct(struct PacketTable *self)
{
    tree_free(&self->lengths, NULL);
}

struct PacketLengthInfo *packet_table_get_length(struct PacketTable *self,
                                                          struct PacketLengthInfo *out, int id)
{
    struct PacketLengthEntry *entry = tree_find(&self->lengths, &id, tree_less_int);

    if (entry) {
        if (entry->length.size == PACKET_VARIABLE) {
            out->kind = PACKET_KIND_VARIABLE;
            out->length = entry->length.min_size;
            return out;
        }
        if (entry->length.size >= 0) {
            out->kind = PACKET_KIND_FIXED;
            out->length = entry->length.size;
            return out;
        }
    }
    out->kind = PACKET_KIND_UNKNOWN;
    out->length = 4;
    return out;
}
