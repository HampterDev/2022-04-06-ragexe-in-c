void *object_as_type(void *object, enum ObjectType type)
{
    const void *table;
    size_t i;
    uint32_t requested;
    if (!object || (unsigned)type >= OBJECT_TYPE_COUNT)
        return NULL;
    memcpy(&table, object, sizeof(table));
    requested = UINT32_C(1) << type;
    for (i = 0; i < sizeof(object_types) / sizeof(object_types[0]); ++i) {
        if (object_types[i].table == table)
            return object_types[i].types & requested ? object : NULL;
    }
    return NULL;
}

const char *object_type_name(const void *table)
{
    size_t i;
    for (i = 0; i < sizeof(object_types) / sizeof(object_types[0]); ++i) {
        if (object_types[i].table == table)
            return object_types[i].name;
    }
    return "?";
}
