void session_init_pet_emotions(struct Session *self)
{
    int hunger, intimacy, action;

    for (hunger = 0; hunger < 5; hunger++)
        for (intimacy = 0; intimacy < 5; intimacy++)
            for (action = 0; action < 7; action++) {
                if (intimacy == 0 && action == 6)
                    continue;
                self->petEmotion[hunger][intimacy][action] = s_petEmotions[hunger][intimacy][action];
            }
}

void session_load_monster_skill_info(struct Session *self)
{
    struct File skills;

    file_construct(&skills);
    if (file_open(&skills, "MonsterSkillInfo.xml", 0, 1, 0)) {
        xml_parse(&self->monsterSkillTable, (const char *)skills.buffer,
                  (const char *)skills.buffer + skills.size);
        file_close(&skills);
    }

    file_destruct(&skills);
}


