void session_load_talk_tables(struct Session *self)
{
    struct File pet, skills, talk;

    file_construct(&pet);
    file_open(&pet, language_language_file(g_language, "PetTalkTable.xml"), 0, 1, 0);
    xml_parse(&self->petTalkTable, (const char *)pet.buffer, (const char *)pet.buffer + pet.size);
    file_close(&pet);

    file_construct(&skills);
    if (file_open(&skills, "MonsterSkillInfo.xml", 0, 1, 0)) {
        xml_parse(&self->monsterSkillTable, (const char *)skills.buffer,
                  (const char *)skills.buffer + skills.size);
        file_close(&skills);
    }

    file_construct(&talk);
    if (file_open(&talk, "MonsterTalkTable.xml", 0, 1, 0)) {
        xml_parse(&self->monsterTalkTable, (const char *)talk.buffer, (const char *)talk.buffer + talk.size);
        file_close(&talk);
    }

    file_destruct(&talk);
    file_destruct(&skills);
    file_destruct(&pet);
}

void session_load_map_info_table(struct Session *self)
{
    struct File file;

    file_construct(&file);
    if (!file_open(&file, "MapInfoTable.scp", 0, 1, 0)) {
        if (g_serviceType == 0)
            error_msg("Load MapInfoTable Failed!", 0);
        else
            map_property_mgr_clear(g_mapFlags);
    } else {
        int size = file.size;
        char *text = (char *)mem_alloc((size_t)size + 1);
        int pos = 0, row = 0, column = 0;

        if (file_read(&file, text, size)) {
            text[size] = 0;
            while (pos < size && row < 30) {
                int start, valid;
                char saved, *end;
                long value;

                if (isspace((unsigned char)text[pos])) {
                    pos++;
                    continue;
                }
                if (text[pos] == '/' && pos < size - 1) {
                    if (text[pos + 1] == '/') {
                        pos += 2;
                        while (pos < size && text[pos] != '\n')
                            pos++;
                        continue;
                    }
                    if (text[pos + 1] == '*') {
                        pos += 2;
                        while (pos < size - 1 && !(text[pos] == '*' && text[pos + 1] == '/'))
                            pos++;
                        if (pos >= size - 1)
                            break;
                        pos += 2;
                        continue;
                    }
                }
                start = pos;
                while (pos < size && !isspace((unsigned char)text[pos]) && text[pos] != '/')
                    pos++;
                saved = text[pos];
                text[pos] = 0;
                errno = 0;
                value = strtol(text + start, &end, 10);
                valid = end != text + start && *end == 0 && errno != ERANGE
                    && value >= INT_MIN && value <= INT_MAX;
                text[pos] = saved;
                if (!valid)
                    break;
                map_property_mgr_set(g_mapFlags, row, column, (int)value);
                if (++column >= 27) {
                    row++;
                    column = 0;
                }
            }
        }
        mem_free(text);
        file_close(&file);
    }
    file_destruct(&file);
}

