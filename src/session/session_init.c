static void fill_int_map(struct Tree *map, const struct IntIntPair *pairs, size_t count)
{
    size_t i;

    tree_clear(map, NULL);
    for (i = 0; i < count; i++) {
        struct IntIntPair *pair = tree_get(map, &pairs[i].key, sizeof pairs[i].key, sizeof *pair, tree_less_int);

        pair->value = pairs[i].value;
    }
}

