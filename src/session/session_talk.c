#define COUNT(a) (sizeof(a) / sizeof((a)[0]))

static void push_named(struct Vec *v, const char *name, int value)
{
    struct NamedInt e;

    e.name = name;
    e.value = value;
    vec_push(v, &e, sizeof e);
}

static void push_commands(struct Vec *v, const struct TalkCommand *c, size_t n)
{
    size_t i;

    for (i = 0; i < n; i++)
        push_named(v, c[i].text ? c[i].text : msg_str(c[i].msgId), c[i].type);
}

static unsigned char less_name(const void *a, const void *b, void *pred)
{
    return strcmp(((const struct NamedInt *)a)->name, ((const struct NamedInt *)b)->name) < 0;
}

void session_init_talk_type_table_(struct Session *self)
{
    size_t i;

    push_commands(&self->talkTypes, s_commands, COUNT(s_commands));
    if (g_serverType != 3)
        push_commands(&self->talkTypes, s_shiftCommands, COUNT(s_shiftCommands));
    push_commands(&self->talkTypes, s_moreCommands, COUNT(s_moreCommands));
    std_stable_sort(self->talkTypes.first, self->talkTypes.last, sizeof(struct NamedInt), less_name, NULL);

    for (i = 0; i < COUNT(s_commandListCommands); i++)
        push_named(&self->commandListCommands, s_commandListCommands[i].name, s_commandListCommands[i].value);
    for (i = 0; i < COUNT(s_windowNames); i++)
        push_named(&self->windowNames, s_windowNames[i].name, s_windowNames[i].value);
    for (i = 0; i < COUNT(s_altKeys); i++)
        vec_push(&self->altKeyNames, &s_altKeys[i], sizeof s_altKeys[i]);
}
