"""Write src/platform/code_page_tables.c: the client's Windows code pages as tables.

Android's C library converts only between Unicode forms, so the Android client carries the code
pages it can select itself. The tables are read from Windows, the system the client was made for:
every byte and byte pair through MultiByteToWideChar, and, where several codes decode to the same
character, the code WideCharToMultiByte picks for it. Run on Windows:

    python tools/code_pages.py
"""
import argparse
import ctypes
import pathlib
import sys

CODE_PAGES = (874, 932, 936, 949, 950, 1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258)
DOUBLE_BYTE = (932, 936, 949, 950)
LEAD_FIRST, LEAD_LAST = 0x81, 0xFE
TRAIL_FIRST, TRAIL_LAST = 0x40, 0xFE
MB_ERR_INVALID_CHARS = 0x8
WC_NO_BEST_FIT_CHARS = 0x400

ROOT = pathlib.Path(__file__).resolve().parent.parent


def windows():
    if sys.platform != 'win32':
        sys.exit('code_pages.py reads the tables from Windows; run it there')
    return ctypes.windll.kernel32


def decode(kernel, code_page, data):
    out = ctypes.create_unicode_buffer(4)
    n = kernel.MultiByteToWideChar(code_page, MB_ERR_INVALID_CHARS, data, len(data), out, 4)
    return ord(out[0]) if n == 1 and ord(out[0]) else 0


def encode(kernel, code_page, char):
    text = chr(char)
    out = ctypes.create_string_buffer(4)
    used = ctypes.c_int(0)
    n = kernel.WideCharToMultiByte(code_page, WC_NO_BEST_FIT_CHARS, text, 1, out, 4, None, ctypes.byref(used))
    return out.raw[:n] if n and not used.value else None


def code_bytes(code):
    return bytes([code]) if code < 0x100 else bytes([code >> 8, code & 0xFF])


def page_tables(kernel, code_page):
    single = [decode(kernel, code_page, bytes([b])) for b in range(0x80, 0x100)]
    double = []
    if code_page in DOUBLE_BYTE:
        for lead in range(LEAD_FIRST, LEAD_LAST + 1):
            for trail in range(TRAIL_FIRST, TRAIL_LAST + 1):
                double.append(decode(kernel, code_page, bytes([lead, trail])))
    codes = {}
    for i, char in enumerate(single):
        if char:
            codes.setdefault(char, []).append(0x80 + i)
    rows = TRAIL_LAST - TRAIL_FIRST + 1
    for i, char in enumerate(double):
        if char:
            codes.setdefault(char, []).append((LEAD_FIRST + i // rows) << 8 | (TRAIL_FIRST + i % rows))
    decode_only = []
    for char, choices in sorted(codes.items()):
        if len(choices) < 2:
            continue
        picked = encode(kernel, code_page, char)
        decode_only.extend(code for code in choices if code_bytes(code) != picked)
    return single, double, sorted(decode_only)


def array(name, values, per_line=16):
    lines = ['static const uint16_t %s[%d] = {' % (name, len(values))]
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join('0x%x' % v if v else '0' for v in values[i:i + per_line]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--out', type=pathlib.Path, default=ROOT / 'src' / 'platform' / 'code_page_tables.c')
    args = parser.parse_args()
    kernel = windows()
    parts = ['/* Generated by tools/code_pages.py from Windows; do not edit. */',
             '#include "platform/iconv_port.h"', '#ifdef RAGE_OWN_ICONV',
             '#include "platform/code_page_tables.h"', '']
    entries = []
    for code_page in CODE_PAGES:
        single, double, decode_only = page_tables(kernel, code_page)
        parts.append(array('single_%d' % code_page, single))
        double_name = decode_only_name = 'NULL'
        if double:
            double_name = 'double_%d' % code_page
            parts.append(array(double_name, double))
        if decode_only:
            decode_only_name = 'decode_only_%d' % code_page
            parts.append(array(decode_only_name, decode_only, 8))
        entries.append('    {%d, single_%d, %s, %s, %d},' % (code_page, code_page, double_name, decode_only_name,
                                                             len(decode_only)))
        parts.append('')
    parts.append('const struct CodePageTable code_page_tables[] = {')
    parts.extend(entries)
    parts.append('};')
    parts.append('const size_t code_page_table_count = sizeof code_page_tables / sizeof code_page_tables[0];')
    parts.append('#endif')
    args.out.write_text('\n'.join(parts) + '\n', encoding='ascii', newline='\n')
    print('wrote', args.out, args.out.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
