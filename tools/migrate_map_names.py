"""Convert one extracted mapNameTable.txt into a standalone Lua map catalog."""

import argparse
import hashlib
from pathlib import Path


MARKER = b"-- Generated by tools/migrate_map_names.py"


def read_names(data):
    """Read hash-delimited pairs without transcoding the client's text bytes."""
    if b"\0" in data or data.startswith((b"\xef\xbb\xbf", b"\xff\xfe", b"\xfe\xff")):
        raise ValueError("Use the original client encoding, without a BOM or NUL bytes")
    names = {}
    for number, line in enumerate(data.replace(b"\r\n", b"\n").replace(b"\r", b"\n").split(b"\n"), 1):
        if not line or line.startswith(b"//"):
            continue
        fields = line.split(b"#")
        if fields[-1] or len(fields) % 2 != 1:
            raise ValueError(f"Line {number}: expected complete map#name# pairs")
        for index in range(0, len(fields) - 1, 2):
            key, value = fields[index:index + 2]
            if not key:
                raise ValueError(f"Line {number}: empty map identifier")
            names[key] = value  # Match the old loader's last-entry-wins behavior.
    if not names:
        raise ValueError("The text catalog contains no map names")
    return names


def lua_string(value):
    # Three-digit escapes cannot absorb a following digit or depend on encoding.
    return '"' + ''.join(
        chr(byte) if 32 <= byte < 127 and byte not in (34, 92)
        else f"\\{byte:03d}" for byte in value
    ) + '"'


def convert(data, base=b""):
    if base.startswith(b"\x1bLua"):
        raise ValueError("--base requires Lua source, not compiled bytecode")
    if MARKER in base:
        raise ValueError("Use the original Lua source as --base, not a previous conversion")
    names = read_names(data)
    lines = [MARKER.decode(), "-- Text catalog SHA-256: " + hashlib.sha256(data).hexdigest()]
    header = ('\n'.join(lines) + '\n').encode('ascii')
    lines = ["", "local converted_map_names = {"]
    for key, value in sorted(names.items()):
        lines.append(f"  [{lua_string(key)}] = {lua_string(value)},")
    lines += [
        "}",
        "local existing_main = main",
        "function main()",
        "  for map, name in pairs(converted_map_names) do",
        "    local ok, message = AddMapDisplayName(map, name)",
        "    if not ok then return ok, message end",
        "  end",
        "  if existing_main then return existing_main() end",
        '  return true, "good"',
        "end",
        "",
    ]
    # Preserve existing Lua code byte-for-byte. Its main runs after the converted
    # names, retaining the original precedence for name overrides.
    return header + base + b"\n" + '\n'.join(lines).encode('ascii')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("table", type=Path, help="Extracted mapNameTable.txt actually used by the client")
    parser.add_argument("--base", type=Path, help="Existing mapInfo_true.lub as Lua source (optional)")
    parser.add_argument("--output", type=Path, required=True, help="New output file; existing files are not overwritten")
    args = parser.parse_args()
    try:
        data = args.table.read_bytes()
        output = convert(data, args.base.read_bytes() if args.base else b"")
        with args.output.open('xb') as stream:
            stream.write(output)
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Converted {len(read_names(data))} unique map names to {args.output}")


if __name__ == "__main__":
    main()
