/* bin2c: writes files as C byte arrays, so that data the client reads at run time is
   compiled into the executable instead of being shipped beside it.

       bin2c OUT.c NAME FILE [NAME FILE ...]

   For every NAME it defines `const unsigned char NAME[]` with the bytes of FILE and a
   terminating 0, and `const size_t NAME_size` with the byte count without that 0. Plain
   C99 and the standard library only, so the same source builds with MSVC (build.bat) and
   with GCC or Clang (the Linux and macOS port). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int embed(FILE *out, const char *name, const char *path)
{
    FILE *in = fopen(path, "rb");
    unsigned long count = 0;
    int c;

    if (!in) {
        fprintf(stderr, "bin2c: cannot read %s\n", path);
        return 0;
    }
    fprintf(out, "\nconst unsigned char %s[] = {", name);
    while ((c = getc(in)) != EOF) {
        fprintf(out, "%s0x%02x,", count % 16 ? " " : "\n    ", c);
        ++count;
    }
    fprintf(out, "%s0x00\n};\nconst size_t %s_size = %lu;\n", count % 16 ? " " : "\n    ", name, count);
    if (ferror(in)) {
        fprintf(stderr, "bin2c: error reading %s\n", path);
        fclose(in);
        return 0;
    }
    fclose(in);
    return 1;
}

int main(int argc, char **argv)
{
    FILE *out;
    int i, ok = 1;

    if (argc < 4 || argc % 2) {
        fprintf(stderr, "usage: bin2c OUT.c NAME FILE [NAME FILE ...]\n");
        return 2;
    }
    out = fopen(argv[1], "w");
    if (!out) {
        fprintf(stderr, "bin2c: cannot write %s\n", argv[1]);
        return 1;
    }
    fprintf(out, "/* Generated by tools/bin2c.c; do not edit. */\n#include <stddef.h>\n");
    for (i = 2; i < argc && ok; i += 2)
        ok = embed(out, argv[i], argv[i + 1]);
    if (fclose(out) != 0)
        ok = 0;
    if (!ok)
        remove(argv[1]);
    return ok ? 0 : 1;
}
